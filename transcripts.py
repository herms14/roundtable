#!/usr/bin/env python3
"""Conversation transcripts -> Obsidian vault.

Every conversation turn with a Roundtable agent (Discord chat, delegated asks, portal/voice calls) is appended to the
`transcripts` table by `olympus_core.transcript()`. `export` (timer, every 15 min) renders one Markdown note per agent
per day (Manila time) and uploads it with rclone:
  * Roundtable agents -> AI/Transcripts/Roundtable/YYYY/MM/YYYY-MM-DD - <Agent>.md
  * private agents    -> AI/Personal/<Agent> - Conversations/YYYY/MM/YYYY-MM-DD - <Agent>.md
Only days with new turns are re-rendered. Anything written below the `transcript:end` marker in a note (review notes,
assessments) is preserved on re-render. Obvious secrets are masked.

CLI: export [--all] | backfill | stats | show <agent> [YYYY-MM-DD]
"""
import argparse
import contextlib
import datetime as dt
import fcntl
import os
import re
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

import olympus_core as o

AGENT = "transcripts"
REMOTE = os.environ.get("DOC_AGENT_REMOTE", "onedrive:Obsidian Vault/Hermes's Life Knowledge Base")
ROOT_REL = "AI/Transcripts/Roundtable"
PRIVATE = {a["id"]: f"AI/Personal/{a['name']} - Conversations" for a in o.registry()["agents"]
           if a.get("group") in ("personal", "specialized")}
KV = "transcripts_exported_id"
NO_VAULT = set()  # agent ids whose conversations stay on the server, never in the OneDrive vault
LOCK = o.DATA_DIR / "transcripts.lock"
MARK_START, MARK_END = "<!-- transcript:start -->", "<!-- transcript:end -->"
REVIEW_STUB = "\n\n## 📝 Review notes\n\n*Your assessment of this day's conversations (kept when the transcript refreshes).*\n"
SECRET_RE = re.compile(r"(sk-[A-Za-z0-9_-]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|glpat-[A-Za-z0-9_-]{16,}|"
                       r"xox[abpr]-[A-Za-z0-9-]{10,}|eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]+|"
                       r"(?i:(?:password|passwd|api[_ -]?key|token|secret)\s*[:=]\s*)\S+)")


@contextlib.contextmanager
def _lock():
    o.DATA_DIR.mkdir(parents=True, exist_ok=True)
    with open(LOCK, "w") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(f, fcntl.LOCK_UN)


def _rclone(*args, timeout=180):
    return subprocess.run(["rclone", "--retries", "3", *args], capture_output=True, text=True, timeout=timeout)


def _mask(text):
    def sub(m):
        s = m.group(0)
        k = re.match(r"(?i)(password|passwd|api[_ -]?key|token|secret)\s*[:=]\s*", s)
        return (k.group(0) if k else "") + "‹redacted›"
    return SECRET_RE.sub(sub, text or "")


def _name(aid):
    try:
        return o.agent_info(aid).get("name", aid)
    except Exception:  # noqa: BLE001
        return aid


def _emoji(aid):
    try:
        e = o.agent_info(aid).get("emoji", "💬")
        return e if not e.startswith("<") else "💬"
    except Exception:  # noqa: BLE001
        return "💬"


def _day_bounds(day):
    start = dt.datetime.combine(day, dt.time(0), tzinfo=o.TZ)
    return o.iso(start), o.iso(start + dt.timedelta(days=1))


def note_rel(aid, day):
    base = PRIVATE.get(aid, ROOT_REL)
    return f"{base}/{day:%Y}/{day:%m}/{day:%Y-%m-%d} - {_name(aid)}.md"


def render(aid, day, rows):
    name = _name(aid)
    sessions = defaultdict(list)
    for r in rows:
        sessions[(r["source"], r["session"] or f"t{r['id']}")].append(r)
    groups = sorted(sessions.items(), key=lambda kv: kv[1][0]["id"])
    sources = sorted({(r["source"] or "").split(" ")[0] for r in rows})
    words = sum(len((r["text"] or "").split()) for r in rows)
    speakers = sorted({r["speaker"] for r in rows})
    first, last = o.local(o.parse_iso(rows[0]["ts"])), o.local(o.parse_iso(rows[-1]["ts"]))
    tags = ["type/session-log", "source/claude", "roundtable/transcript", f"agent/{aid}"]
    tags.append("domain/personal" if aid in PRIVATE else "domain/homelab")
    fm = ["---", f"tags: [{', '.join(tags)}]", f"created: {day:%Y-%m-%d}", f"updated: {o.local():%Y-%m-%d}",
          "type: session-log", "status: seed", "kind: transcript", f"agent: \"{name}\"", f"agent_id: {aid}",
          f"date: {day:%Y-%m-%d}", f"conversations: {len(groups)}", f"turns: {len(rows)}", f"words: {words}",
          f"sources: [{', '.join(sources)}]",
          "related: [\"[[AI/Transcripts/62 - Roundtable Transcripts]]\"]" if aid not in PRIVATE else
          "related: [\"[[AI/Documentation/60 - Roundtable Agent Team]]\"]", "---", ""]
    out = [f"# {_emoji(aid)} {name} — conversations {day:%A %d %B %Y}", "",
           f"> [!info] {len(groups)} conversation(s) · {len(rows)} turns · {words} words · "
           f"{first:%H:%M}–{last:%H:%M} Manila · {', '.join(sources)}",
           "> Auto-generated by `transcripts.py` from the Roundtable ledger. Secrets are masked. "
           "Add your review below the line — it is kept on refresh.", ""]
    if aid in PRIVATE:
        out += [f"> [!warning] Private — conversations with {name}. Not shared with other agents.", ""]
    out.append(MARK_START)
    for (source, session), turns in groups:
        t0 = o.local(o.parse_iso(turns[0]["ts"]))
        chan = turns[0]["channel"]
        where = f"#{chan}" if chan and not chan.isdigit() and source == "discord" else ""
        label = "🎙️ Voice" if (source or "").startswith("voice") else "💬 Discord"
        extra = f" ({source.split('(', 1)[1].rstrip(')')})" if "(" in (source or "") else ""
        out += ["", f"## {t0:%H:%M} · {label}{extra} {where}".rstrip(), ""]
        for t in turns:
            ts = o.local(o.parse_iso(t["ts"]))
            text = _mask(t["text"]).replace("\n", "\n> ")
            who = t["speaker"] or "?"
            icon = "🧑" if who in ("Master Hermes", "Hermes") else ("📨" if who == "Request" else _emoji(aid))
            out.append(f"> **{icon} {who}** · <small>{ts:%H:%M:%S}</small>\n> {text}\n")
    out += ["", MARK_END]
    return "\n".join(fm + out)


def _existing_tail(rel):
    r = _rclone("cat", f"{REMOTE}/{rel}", timeout=60)
    if r.returncode != 0 or MARK_END not in r.stdout:
        return REVIEW_STUB
    tail = r.stdout.split(MARK_END, 1)[1]
    return tail if tail.strip() else REVIEW_STUB


def _rows(con, aid, day):
    a, b = _day_bounds(day)
    return con.execute("SELECT * FROM transcripts WHERE agent=? AND ts>=? AND ts<? ORDER BY id", (aid, a, b)).fetchall()


def export(all_days=False):
    with _lock(), contextlib.closing(o.db()) as con:
        last = 0 if all_days else int(o.kv_get(KV, 0) or 0)
        new = con.execute("SELECT id, ts, agent FROM transcripts WHERE id>? ORDER BY id", (last,)).fetchall()
        if not new:
            return 0
        todo = {(r["agent"], o.local(o.parse_iso(r["ts"])).date()) for r in new}
        top = max(r["id"] for r in new)
        ok = 0
        with tempfile.TemporaryDirectory() as tmp:
            for aid, day in sorted(todo, key=lambda x: (x[1], x[0])):
                if aid in NO_VAULT:
                    continue
                rows = _rows(con, aid, day)
                if not rows:
                    continue
                rel = note_rel(aid, day)
                body = render(aid, day, rows) + _existing_tail(rel)
                p = Path(tmp) / "note.md"
                p.write_text(body, encoding="utf-8")
                r = _rclone("copyto", str(p), f"{REMOTE}/{rel}")
                if r.returncode != 0:
                    o.log(AGENT, f"upload failed {rel}: {r.stderr[-300:]}")
                    return ok  # keep the cursor; retry next run
                ok += 1
        o.kv_set(KV, top)
        o.log(AGENT, f"exported {ok} note(s) up to transcript #{top}")
        return ok


_LINE = re.compile(r"^\*\*(.+?):\*\*\s?(.*)$")


def backfill():
    """Import past voice calls (ledger `detail`) that predate transcript logging."""
    n = 0
    with contextlib.closing(o.db()) as con, con:
        seen = {r["session"] for r in con.execute("SELECT DISTINCT session FROM transcripts")}
        for run in con.execute("SELECT id, agent, task, started, detail FROM runs WHERE trigger='voice' AND detail "
                               "IS NOT NULL AND detail NOT LIKE '(private%' ORDER BY id").fetchall():
            sess = f"voice-{run['id']}"
            if sess in seen:
                continue
            src = "voice (portal)" if "(portal)" in (run["task"] or "") else "voice"
            cur = None
            for line in run["detail"].splitlines():
                m = _LINE.match(line)
                if m:
                    if cur:
                        n += _ins(con, run, src, sess, *cur)
                    who = "Master Hermes" if m.group(1) == "Hermes" else m.group(1)
                    cur = [who, m.group(2)]
                elif cur:
                    cur[1] += "\n" + line
            if cur:
                n += _ins(con, run, src, sess, *cur)
    print(f"backfilled {n} turns")
    return n


def _ins(con, run, src, sess, who, text):
    if not text.strip():
        return 0
    con.execute("INSERT INTO transcripts(ts, agent, source, channel, session, speaker, text) VALUES(?,?,?,?,?,?,?)",
                (run["started"], run["agent"], src, "", sess, who, text.strip()))
    return 1


def stats():
    with contextlib.closing(o.db()) as con:
        for r in con.execute("SELECT agent, COUNT(*) n, COUNT(DISTINCT session) s, MIN(ts) a, MAX(ts) b "
                             "FROM transcripts GROUP BY agent ORDER BY n DESC"):
            print(f"{_name(r['agent']):<16} {r['n']:>5} turns {r['s']:>4} convs  {r['a']} → {r['b']}")
    print(f"exported up to #{o.kv_get(KV, 0)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["export", "backfill", "stats", "show"])
    ap.add_argument("agent", nargs="?")
    ap.add_argument("day", nargs="?")
    ap.add_argument("--all", action="store_true", help="re-render every day")
    a = ap.parse_args()
    if a.cmd == "export":
        print(f"exported {export(a.all)} note(s)")
    elif a.cmd == "backfill":
        backfill()
    elif a.cmd == "stats":
        stats()
    else:
        day = dt.date.fromisoformat(a.day) if a.day else o.local().date()
        with contextlib.closing(o.db()) as con:
            rows = _rows(con, a.agent, day)
        print(render(a.agent, day, rows) if rows else "no turns")


if __name__ == "__main__":
    sys.exit(main())
